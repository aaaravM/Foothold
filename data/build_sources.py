#!/usr/bin/env python3
"""Merge data/processed/sources/*.json into data/processed/sources.json and regenerate data/SOURCES.md.

One file per producer (build_processed.py writes sources/onet.json; other build steps add their own,
e.g. sources/wages.json, sources/programs.json, sources/synthetic.json) and then re-run:
    $FOOTHOLD_PY data/build_sources.py

Producer file format: a JSON list of source records, or {"sources": [...]}. Required fields per record:
    id         snake_case, unique across all producers (processed files reference it as source_id)
    title      what the dataset is
    url        official URL (or a repo path such as data/build_processed.py for Foothold-made datasets)
    publisher  who published it
    license    license or terms ("Public web page; facts only", "CC BY 4.0", ...)
    retrieved  YYYY-MM-DD when it was read, or null for Foothold-made data
    status     REAL | SAMPLE | SYNTHETIC | FICTIONAL
Optional fields rendered in SOURCES.md: license_url, attribution (credit line shown verbatim), modified,
modifications [..], methods {title: text}, notes (string or list), files [{file, url, rows, sha256}],
providers [..], used_by [processed file names].

Duplicate ids: the first producer file (alphabetical order) wins; differing duplicates are reported.
Output is deterministic (no timestamps), so re-running without changes produces identical files.
"""

from __future__ import annotations

import json
import os
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROCESSED = ROOT / "data" / "processed"
SOURCES_DIR = PROCESSED / "sources"
OUT_JSON = PROCESSED / "sources.json"
OUT_MD = ROOT / "data" / "SOURCES.md"

REQUIRED = ["id", "title", "url", "publisher", "license", "retrieved", "status"]
STATUSES = ["REAL", "SAMPLE", "SYNTHETIC", "FICTIONAL"]
LABELS = {
    "REAL": "read from an official source on the retrieval date (URL and date given)",
    "SAMPLE": "plausible placeholder, NOT verified; check the linked page before treating it as fact",
    "SYNTHETIC": "generated by Foothold scripts",
    "FICTIONAL": "invented people, employers, and communities",
}


def write_text(path: Path, text: str) -> None:
    """Atomic write so readers never see a half-written file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    for attempt in range(8):
        try:
            os.replace(tmp, path)
            return
        except PermissionError:
            time.sleep(0.25 * (attempt + 1))
    os.replace(tmp, path)


def md(value) -> str:
    """Make a value safe for a Markdown table cell."""
    if value is None:
        return "n/a"
    s = str(value).replace("\r", " ").replace("\n", " ").replace("|", "\\|")
    return s


def link(url) -> str:
    if not url:
        return "n/a"
    url = str(url)
    if url.startswith(("http://", "https://")):
        return f"<{url}>"
    return f"`{url}`"


def load_producers() -> tuple[list[dict], list[str]]:
    records: list[dict] = []
    warnings: list[str] = []
    seen: dict[str, dict] = {}
    if not SOURCES_DIR.exists():
        warnings.append("data/processed/sources/ does not exist; nothing to merge")
        return records, warnings
    for path in sorted(SOURCES_DIR.glob("*.json")):
        rel = f"sources/{path.name}"
        try:
            with open(path, encoding="utf-8") as fh:
                data = json.load(fh)
        except (OSError, json.JSONDecodeError) as e:
            warnings.append(f"{rel}: could not read ({type(e).__name__}: {e}); skipped")
            continue
        items = data.get("sources") if isinstance(data, dict) else data
        if not isinstance(items, list):
            warnings.append(f"{rel}: expected a list of records or {{\"sources\": [...]}}; skipped")
            continue
        for i, rec in enumerate(items):
            if not isinstance(rec, dict):
                warnings.append(f"{rel}[{i}]: not an object; skipped")
                continue
            missing = [k for k in REQUIRED if k not in rec]
            if missing:
                warnings.append(f"{rel}: record {rec.get('id', i)!r} is missing {missing}")
            if rec.get("status") not in STATUSES:
                warnings.append(f"{rel}: record {rec.get('id', i)!r} has status {rec.get('status')!r} (expected one of {STATUSES})")
            sid = rec.get("id")
            if not sid:
                warnings.append(f"{rel}[{i}]: record without id; skipped")
                continue
            if sid in seen:
                first = seen[sid]
                same = {k: v for k, v in first.items() if k != "producer_file"} == rec
                if not same:
                    warnings.append(f"duplicate id {sid!r}: kept {first['producer_file']}, ignored a different record in {rel}")
                continue
            out = dict(rec)
            out["producer_file"] = rel
            seen[sid] = out
            records.append(out)
    return records, warnings


def render_md(records: list[dict], warnings: list[str]) -> str:
    L: list[str] = []
    add = L.append
    add("# Foothold data sources")
    add("")
    add("Generated by `data/build_sources.py` from `data/processed/sources/*.json` (one file per producer). "
        "Do not edit by hand: change the producer file and re-run.")
    add("")
    add("```bash")
    add("$FOOTHOLD_PY data/build_processed.py      # O*NET backbone, skills, courses, jobs (add --verify-courses to re-check pages)")
    add("$FOOTHOLD_PY data/build_sources.py        # this file + data/processed/sources.json")
    add("$FOOTHOLD_PY data/validate.py             # check every processed file")
    add("```")
    add("")
    add("## Provenance labels")
    add("")
    for k in STATUSES:
        add(f"- **{k}**: {LABELS[k]}.")
    add("")
    add("Every displayed wage, cost, duration, or program detail carries one of these labels and a `source_id` "
        "that points to a record below.")
    add("")

    attributed = [r for r in records if r.get("attribution")]
    if attributed:
        add("## Required attributions")
        add("")
        for r in attributed:
            add(f"**{md(r.get('title'))}** (`{r['id']}`)")
            add("")
            add(f"> {r['attribution']}")
            add("")
            if r.get("license_url"):
                add(f"License: [{md(r.get('license'))}]({r['license_url']})"
                    + (f" (license page: <{r['license_page']}>)" if r.get("license_page") else ""))
                add("")
            if r.get("modified"):
                add("Foothold modified this data. Changes:")
                add("")
                for m in r.get("modifications") or []:
                    add(f"- {m}")
                add("")

    with_methods = [r for r in records if r.get("methods")]
    if with_methods:
        add("## Methods")
        add("")
        for r in with_methods:
            for title, text in r["methods"].items():
                add(f"### {title}")
                add("")
                add(f"{text} (source: `{r['id']}`)")
                add("")

    add("## Datasets")
    add("")
    add("| id | dataset | status | license | retrieved | URL | producer |")
    add("|---|---|---|---|---|---|---|")
    for r in records:
        add(f"| `{md(r.get('id'))}` | {md(r.get('title'))} | {md(r.get('status'))} | {md(r.get('license'))} | "
            f"{md(r.get('retrieved'))} | {link(r.get('url'))} | `{md(r.get('producer_file'))}` |")
    add("")

    used: dict[str, list[str]] = {}
    for r in records:
        for f in r.get("used_by") or []:
            used.setdefault(f, []).append(r["id"])
    if used:
        add("## Processed files and their sources")
        add("")
        add("| file | source ids |")
        add("|---|---|")
        for f in sorted(used):
            add(f"| `{md(f)}` | {', '.join(f'`{s}`' for s in used[f])} |")
        add("")

    add("## Details")
    add("")
    for r in records:
        add(f"### `{r['id']}`: {md(r.get('title'))}")
        add("")
        add(f"- URL: {link(r.get('url'))}")
        add(f"- Publisher: {md(r.get('publisher'))}")
        lic = md(r.get("license"))
        if r.get("license_url"):
            lic = f"[{lic}]({r['license_url']})"
        add(f"- License / terms: {lic}")
        add(f"- Retrieved: {md(r.get('retrieved'))}")
        add(f"- Status: **{md(r.get('status'))}**")
        add(f"- Producer file: `{md(r.get('producer_file'))}`" + (f" (built by `{r['producer']}`)" if r.get("producer") else ""))
        if r.get("used_by"):
            add(f"- Used by: {', '.join(f'`{u}`' for u in r['used_by'])}")
        notes = r.get("notes")
        if isinstance(notes, list):
            for n in notes:
                add(f"- Note: {n}")
        elif notes:
            add(f"- Note: {notes}")
        if r.get("files"):
            add("")
            add("| file | rows | sha256 | URL |")
            add("|---|---:|---|---|")
            for f in r["files"]:
                add(f"| `{md(f.get('file'))}` | {md(f.get('rows'))} | `{md(str(f.get('sha256', ''))[:16])}` | {link(f.get('url'))} |")
        if r.get("providers"):
            add("")
            add("Providers:")
            add("")
            for p in r["providers"]:
                add(f"- {md(p)}")
        add("")

    add("## Adding a source")
    add("")
    add("1. Write `data/processed/sources/<producer>.json`: a JSON list of records (or `{\"sources\": [...]}`). "
        "Required fields: `id` (snake_case, unique across producers), `title`, `url`, `publisher`, `license`, "
        "`retrieved` (YYYY-MM-DD, or null for Foothold-made data), `status` (REAL, SAMPLE, SYNTHETIC or FICTIONAL). "
        "Optional: `attribution` (credit line shown verbatim), `license_url`, `modified`, `modifications`, "
        "`methods`, `notes`, `files`, `providers`, `used_by`.")
    add("2. Point each processed record at it with `source_id` (and give it a `status`).")
    add("3. Re-run `data/build_sources.py`, then `data/validate.py`. On an id clash the first producer file in "
        "alphabetical order wins and the clash is listed under Merge warnings.")
    add("")
    if warnings:
        add("## Merge warnings")
        add("")
        for w in warnings:
            add(f"- {w}")
        add("")
    return "\n".join(L).rstrip() + "\n"


def main() -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:  # noqa: BLE001
        pass
    records, warnings = load_producers()
    write_text(OUT_JSON, json.dumps(records, indent=2, ensure_ascii=False) + "\n")
    write_text(OUT_MD, render_md(records, warnings))
    by_status: dict[str, int] = {}
    for r in records:
        by_status[r.get("status")] = by_status.get(r.get("status"), 0) + 1
    producers = sorted({r["producer_file"] for r in records})
    print(f"merged {len(records)} source records from {len(producers)} producer file(s) {producers}")
    print(f"  status counts: {by_status}")
    print(f"  wrote {OUT_JSON.relative_to(ROOT)} and {OUT_MD.relative_to(ROOT)}")
    for w in warnings:
        print(f"  ! {w}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
