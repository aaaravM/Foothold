"""SQLite helpers for api/.runtime/foothold.db (consent, postings, circle posts, progress, kanban).

Thread safety: every call opens its own short-lived connection (sqlite3 objects are
never shared between threads); writes are additionally serialized in-process by a
lock, and a 30 s busy timeout covers other processes. Tables are created on first
use (``init_db`` is idempotent and also called at API startup).

Ids are TEXT with a table prefix generated by SQLite when omitted
(``cr_`` consent request, ``po_`` posting, ``cp_`` circle post, ``pl_`` progress).
Timestamps are ISO-8601 UTC strings. Columns ending in ``_json`` hold JSON text;
:func:`insert` / :func:`update` / :func:`upsert` encode dict/list values for them.

    from foothold import db
    row = db.insert("consent_requests", {"employer_id": "tri_valley_freight",
                                         "candidate_id": "tc_014", "posting_id": pid, "message": msg})
    db.update("consent_requests", row["id"], {"status": "accepted", "decided_at": db.now_iso()})
    pending = db.query("SELECT * FROM consent_requests WHERE candidate_id=? AND status='pending'", (cid,))
    db.upsert("kanban", {"learner_id": "maya", "items_json": items, "updated_at": db.now_iso()}, key="learner_id")
"""

from __future__ import annotations

import json
import re
import sqlite3
import threading
from contextlib import contextmanager
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterator, Mapping, Sequence

from . import config

CONSENT_STATUSES = ("pending", "accepted", "declined")

_NOW = "(strftime('%Y-%m-%dT%H:%M:%fZ','now'))"

SCHEMA = f"""
CREATE TABLE IF NOT EXISTS consent_requests (
    id           TEXT PRIMARY KEY NOT NULL DEFAULT ('cr_' || lower(hex(randomblob(6)))),
    employer_id  TEXT NOT NULL,
    candidate_id TEXT NOT NULL,
    posting_id   TEXT,
    message      TEXT NOT NULL DEFAULT '',
    status       TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted', 'declined')),
    created_at   TEXT NOT NULL DEFAULT {_NOW},
    decided_at   TEXT
);
CREATE INDEX IF NOT EXISTS ix_consent_candidate ON consent_requests (candidate_id, status);
CREATE INDEX IF NOT EXISTS ix_consent_employer ON consent_requests (employer_id, status);

CREATE TABLE IF NOT EXISTS postings (
    id               TEXT PRIMARY KEY NOT NULL DEFAULT ('po_' || lower(hex(randomblob(6)))),
    employer_id      TEXT NOT NULL,
    title            TEXT NOT NULL DEFAULT '',
    text_sanitized   TEXT NOT NULL DEFAULT '',
    profile_json     TEXT NOT NULL DEFAULT '{{}}',
    sim_variant_json TEXT NOT NULL DEFAULT '{{}}',
    created_at       TEXT NOT NULL DEFAULT {_NOW}
);
CREATE INDEX IF NOT EXISTS ix_postings_employer ON postings (employer_id, created_at);

CREATE TABLE IF NOT EXISTS circle_posts (
    id                TEXT PRIMARY KEY NOT NULL DEFAULT ('cp_' || lower(hex(randomblob(6)))),
    circle_id         TEXT NOT NULL,
    handle            TEXT NOT NULL,
    text              TEXT NOT NULL,
    moderation_status TEXT NOT NULL DEFAULT 'held',
    moderation_reason TEXT,
    created_at        TEXT NOT NULL DEFAULT {_NOW}
);
CREATE INDEX IF NOT EXISTS ix_circle_posts ON circle_posts (circle_id, created_at);

CREATE TABLE IF NOT EXISTS progress_log (
    id           TEXT PRIMARY KEY NOT NULL DEFAULT ('pl_' || lower(hex(randomblob(6)))),
    learner_id   TEXT NOT NULL,
    kind         TEXT NOT NULL,
    payload_json TEXT NOT NULL DEFAULT '{{}}',
    created_at   TEXT NOT NULL DEFAULT {_NOW}
);
CREATE INDEX IF NOT EXISTS ix_progress_learner ON progress_log (learner_id, created_at);

CREATE TABLE IF NOT EXISTS kanban (
    learner_id TEXT PRIMARY KEY NOT NULL,
    items_json TEXT NOT NULL DEFAULT '[]',
    updated_at TEXT NOT NULL DEFAULT {_NOW}
);
"""

_IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
_write_lock = threading.RLock()
_init_lock = threading.Lock()
_initialized: set[str] = set()


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="milliseconds").replace("+00:00", "Z")


def db_path() -> Path:
    return config.db_path()


def _ident(name: str) -> str:
    if not _IDENT.match(name):
        raise ValueError(f"invalid SQL identifier: {name!r}")
    return name


def _open(path: Path) -> sqlite3.Connection:
    path.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(str(path), timeout=30)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys=ON")
    return conn


def init_db(path: str | Path | None = None) -> Path:
    """Create tables/indexes if missing (idempotent). Returns the db path."""
    p = Path(path) if path else db_path()
    with _init_lock:
        conn = _open(p)
        try:
            conn.execute("PRAGMA journal_mode=WAL")
            conn.executescript(SCHEMA)
            conn.execute("PRAGMA user_version=1")
            conn.commit()
        finally:
            conn.close()
        _initialized.add(str(p.resolve()))
    return p


@contextmanager
def connect(path: str | Path | None = None) -> Iterator[sqlite3.Connection]:
    """Short-lived connection (commit on success, rollback on error, always closed)."""
    p = Path(path) if path else db_path()
    if str(p.resolve()) not in _initialized:
        init_db(p)
    conn = _open(p)
    try:
        yield conn
        conn.commit()
    except BaseException:
        conn.rollback()
        raise
    finally:
        conn.close()


def _encode(column: str, value: Any) -> Any:
    if column.endswith("_json") and not isinstance(value, (str, bytes)) and value is not None:
        return json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    return value


def jloads(text: str | bytes | None, default: Any = None) -> Any:
    """Decode a ``*_json`` column; returns ``default`` for NULL/invalid JSON."""
    if text is None:
        return default
    try:
        return json.loads(text)
    except (TypeError, ValueError):
        return default


def query(sql: str, params: Sequence[Any] | Mapping[str, Any] = ()) -> list[dict[str, Any]]:
    with connect() as conn:
        return [dict(r) for r in conn.execute(sql, params).fetchall()]


def query_one(sql: str, params: Sequence[Any] | Mapping[str, Any] = ()) -> dict[str, Any] | None:
    with connect() as conn:
        row = conn.execute(sql, params).fetchone()
        return dict(row) if row is not None else None


def execute(sql: str, params: Sequence[Any] | Mapping[str, Any] = ()) -> int:
    """Run a write statement; returns rowcount."""
    with _write_lock, connect() as conn:
        return conn.execute(sql, params).rowcount


def insert(table: str, row: Mapping[str, Any]) -> dict[str, Any]:
    """Insert and return the stored row (including generated id / defaults)."""
    cols = [_ident(c) for c in row]
    values = [_encode(c, row[c]) for c in cols]
    if cols:
        sql = f"INSERT INTO {_ident(table)} ({', '.join(cols)}) VALUES ({', '.join('?' for _ in cols)}) RETURNING *"
    else:
        sql = f"INSERT INTO {_ident(table)} DEFAULT VALUES RETURNING *"
    with _write_lock, connect() as conn:
        return dict(conn.execute(sql, values).fetchone())


def update(table: str, id_value: Any, fields: Mapping[str, Any], *, key: str = "id") -> int:
    """``UPDATE table SET fields WHERE key = id_value``; returns rowcount."""
    if not fields:
        return 0
    cols = [_ident(c) for c in fields]
    sql = f"UPDATE {_ident(table)} SET {', '.join(f'{c} = ?' for c in cols)} WHERE {_ident(key)} = ?"
    with _write_lock, connect() as conn:
        return conn.execute(sql, [*(_encode(c, fields[c]) for c in cols), id_value]).rowcount


def upsert(table: str, row: Mapping[str, Any], *, key: str) -> dict[str, Any]:
    """Insert or update on conflict of ``key``; returns the stored row."""
    cols = [_ident(c) for c in row]
    if key not in cols:
        raise ValueError("upsert row must include the key column")
    others = [c for c in cols if c != key]
    conflict = f"DO UPDATE SET {', '.join(f'{c} = excluded.{c}' for c in others)}" if others else "DO NOTHING"
    sql = (
        f"INSERT INTO {_ident(table)} ({', '.join(cols)}) VALUES ({', '.join('?' for _ in cols)}) "
        f"ON CONFLICT({_ident(key)}) {conflict} RETURNING *"
    )
    with _write_lock, connect() as conn:
        found = conn.execute(sql, [_encode(c, row[c]) for c in cols]).fetchone()
        if found is None:  # DO NOTHING path returns no row
            found = conn.execute(f"SELECT * FROM {_ident(table)} WHERE {_ident(key)} = ?", (row[key],)).fetchone()
        return dict(found)
