import * as React from "react";
import { BadgeCheck, Cpu, Drama, FlaskConical, type LucideIcon } from "lucide-react";
import { cn } from "@/lib/utils";
import type { Provenance } from "@/lib/types";
import { Tooltip, TooltipContent, TooltipTrigger } from "@/components/ui/tooltip";

interface ProvenanceMeta {
  explain: string;
  className: string;
  Icon: LucideIcon;
}

export const PROVENANCE_META: Readonly<Record<Provenance, ProvenanceMeta>> = {
  REAL: {
    explain: "Read from an official source, with a link and a retrieval date.",
    className: "text-success border-success/50",
    Icon: BadgeCheck,
  },
  SAMPLE: {
    explain: "Plausible placeholder, not verified. Check the source before relying on it.",
    className: "text-warning border-warning/50",
    Icon: FlaskConical,
  },
  SYNTHETIC: {
    explain: "Generated by Foothold's own scripts for demos and model training.",
    className: "text-info border-info/50",
    Icon: Cpu,
  },
  FICTIONAL: {
    explain: "An invented person or organization.",
    className: "text-ink-muted border-line-strong border-dashed",
    Icon: Drama,
  },
};

export interface ProvenanceBadgeProps {
  status: Provenance;
  /** where to verify; the badge becomes a link that opens it in a new tab */
  href?: string;
  /** extra context for the tooltip, e.g. "BLS OEWS May 2025, Fresno MSA" */
  note?: string;
  className?: string;
}

/**
 * REAL / SAMPLE / SYNTHETIC / FICTIONAL label for every displayed wage, cost or program detail.
 * Hover or focus shows what the label means; with `href` the badge links to the source.
 */
export function ProvenanceBadge({ status, href, note, className }: ProvenanceBadgeProps) {
  const meta = PROVENANCE_META[status];
  const { Icon } = meta;
  const base =
    "label-mono inline-flex h-5 shrink-0 items-center gap-1 rounded-sm border bg-transparent px-1.5 leading-none whitespace-nowrap transition-colors";
  const spoken = `${status} data. ${meta.explain}${note ? ` ${note}` : ""}`;
  const content = (
    <>
      <Icon aria-hidden="true" className="size-3" />
      <span>{status}</span>
    </>
  );

  const trigger = href ? (
    <a
      href={href}
      target="_blank"
      rel="noopener noreferrer"
      aria-label={`${spoken} Verify at the source (opens in a new tab).`}
      className={cn(base, meta.className, "hover:bg-surface-2", className)}
    >
      {content}
    </a>
  ) : (
    <button type="button" aria-label={spoken} className={cn(base, meta.className, "cursor-help", className)}>
      {content}
    </button>
  );

  return (
    <Tooltip>
      <TooltipTrigger asChild>{trigger}</TooltipTrigger>
      <TooltipContent side="top" sideOffset={6} className="max-w-72 flex-col items-start gap-1 text-left">
        <span className="font-mono text-[10px] tracking-[0.12em] uppercase">{status}</span>
        <span>{meta.explain}</span>
        {note ? <span className="opacity-85">{note}</span> : null}
        {href ? <span className="opacity-85">Opens the source to verify ↗</span> : null}
      </TooltipContent>
    </Tooltip>
  );
}
