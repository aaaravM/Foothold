import * as React from "react";
import { BadgeCheck, Cpu, Drama, FlaskConical, Info, type LucideIcon } from "lucide-react";
import { cn } from "@/lib/utils";
import type { Provenance } from "@/lib/types";
import { Tooltip, TooltipContent, TooltipTrigger } from "@/components/ui/tooltip";

interface ProvenanceMeta {
  explain: string;
  className: string;
  Icon: LucideIcon;
}

export const PROVENANCE_META: Readonly<Record<Provenance, ProvenanceMeta>> = {
  REAL: {
    explain: "Read from an official source, with a link and a retrieval date.",
    className: "text-success border-success/50",
    Icon: BadgeCheck,
  },
  SAMPLE: {
    explain: "Plausible placeholder, not verified. Check the source before relying on it.",
    className: "text-warning border-warning/50",
    Icon: FlaskConical,
  },
  SYNTHETIC: {
    explain: "Generated by Foothold's own scripts for demos and model training.",
    className: "text-info border-info/50",
    Icon: Cpu,
  },
  FICTIONAL: {
    explain: "An invented person or organization.",
    className: "text-ink-muted border-line-strong border-dashed",
    Icon: Drama,
  },
};

export interface ProvenanceBadgeProps {
  status: Provenance;
  /** where to verify; the badge becomes a link that opens it in a new tab */
  href?: string;
  /** extra context for the tooltip, e.g. "BLS OEWS May 2025, Fresno MSA" */
  note?: string;
  className?: string;
  /** render a non-interactive label (no tooltip/button), for use inside another button or link */
  plain?: boolean;
}

/**
 * Subtle source hint next to a wage, cost or program detail: a small info icon whose tooltip names the
 * source ("Source: CA EDD OEWS, 2026 Q1"). With `href` it links to the source. No status label is shown
 * in the app; the full sources list lives on /about.
 */
export function ProvenanceBadge({ status, href, note, className, plain }: ProvenanceBadgeProps) {
  const text = note ? `Source: ${note}` : href ? "Source: official data (opens the source)" : status === "REAL" ? "Source: official data" : "Estimate";
  const base = "inline-flex size-4 shrink-0 items-center justify-center rounded-full text-ink-faint transition-colors hover:text-ink";
  const icon = <Info aria-hidden="true" className="size-3" />;

  if (plain) {
    return (
      <span title={text} className={cn(base, className)}>
        {icon}
        <span className="sr-only">{text}</span>
      </span>
    );
  }

  const trigger = href ? (
    <a href={href} target="_blank" rel="noopener noreferrer" aria-label={`${text} (opens in a new tab)`} className={cn(base, className)}>
      {icon}
    </a>
  ) : (
    <button type="button" aria-label={text} className={cn(base, "cursor-help", className)}>
      {icon}
    </button>
  );

  return (
    <Tooltip>
      <TooltipTrigger asChild>{trigger}</TooltipTrigger>
      <TooltipContent side="top" sideOffset={6} className="max-w-72 text-left">
        <span>{text}</span>
      </TooltipContent>
    </Tooltip>
  );
}
